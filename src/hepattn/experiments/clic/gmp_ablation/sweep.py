"""GMP grid-size / placement sweep: the arm registry, config generation, and the result summary.

Every arm is the PHAT16 encoder of configs/bench3 (dim 256, 6 patch blocks, 16 heads, ...) on top of base.yaml and
configs/gmp_ablation/sweep/common.yaml, with ONE thing varied: the `gmp` geometry (2D cell sizes; 3D depth definition
and depth cell), and -- as a separate, controlled factor -- the placement (`gmp_layers`). Backend, recipe, data split,
batch, seed and budget are fixed by common.yaml and the launcher (submit_gmp_sweep.sh).

    python -m hepattn.experiments.clic.gmp_ablation.sweep write-configs      # regenerate configs/gmp_ablation/sweep/
    python -m hepattn.experiments.clic.gmp_ablation.sweep summarize <campaign dir> [--geometry geometry_study.json]
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path

import yaml

CLIC = Path(__file__).resolve().parents[1]
SWEEP_DIR = CLIC / "configs" / "gmp_ablation" / "sweep"

GRID_2D = {"kernel_size": 3, "eta_cell": 0.2, "phi_cells": 32, "eta_max": 5.2}  # the production 2D grid

# arm name -> (gmp geometry or None, depth mode for the data or None, placement: None = all 6 blocks, else block list)
ARMS: dict[str, tuple[dict | None, str | None, list[int] | None]] = {
    "nogmp": (None, None, None),
    "g2d_e020": (GRID_2D, None, None),
    "g2d_e010": (GRID_2D | {"eta_cell": 0.1, "phi_cells": 64}, None, None),
    "g2d_e040": (GRID_2D | {"eta_cell": 0.4, "phi_cells": 16}, None, None),
    "g3d_env_dz100": (GRID_2D | {"depth_cell": 100.0, "depth_kernel_size": 3}, "envelope", None),
    "g3d_env_dz200": (GRID_2D | {"depth_cell": 200.0, "depth_kernel_size": 3}, "envelope", None),
    "g3d_env_dz400": (GRID_2D | {"depth_cell": 400.0, "depth_kernel_size": 3}, "envelope", None),
    "g3d_proj_dz200": (GRID_2D | {"depth_cell": 200.0, "depth_kernel_size": 3}, "projective", None),
    "g3d_comp": (GRID_2D | {"depth_cell": 1.0, "depth_kernel_size": 3}, "compartment", None),
    # track-depth ablation: as g3d_env_dz200, but track-cluster pairs ignore the depth difference (tracks at "any" depth)
    "g3d_env_dz200_trkany": (GRID_2D | {"depth_cell": 200.0, "depth_kernel_size": 3, "depth_wildcard": True}, "envelope", None),
    # placement factor (fixed 2D production grid): GMP only in block 0
    "g2d_e020_early": (GRID_2D, None, [0]),
}

ENCODER = {  # PHAT16, identical to configs/bench3/phat16_gmp_all_production.yaml except the GMP keys
    "num_layers": 6,
    "dim": 256,
    "attn_type": "patch",
    "patch_size": 16,
    "window_size": None,
    "window_wrap": False,
    "score_mod": None,
    "value_residual": True,
    "num_register_tokens": 8,
    "patch_global": True,
    "attn_kwargs": {"num_heads": 16},
    "norm": "FastLayerNorm",
    "layer_scale": None,
    "drop_path": 0.0,
    "qkv_norm": False,
    "hybrid_norm": True,
    "dense_norm_placement": "legacy",
    "dense_kwargs": {"activation": "SwiGLU"},
}


# Arms whose tracks take CLICDataset(gmp_track_depth=...) other than the default "front" (depth 0, the 3D baseline).
# A track depth of "any" needs a GMP with depth_wildcard: test_gmp_sweep_configs pins that pairing.
TRACK_DEPTH = {"g3d_env_dz200_trkany": "any"}


def arm_config(name: str) -> dict:
    gmp, depth, layers = ARMS[name]
    enc = {"gmp_impl": "weightsfirst" if gmp is not None else "production", "gmp_layers": layers, **ENCODER, "gmp": gmp}
    init = {
        "encoder": {"class_path": "hepattn.experiments.clic.a4.PlacementEncoder", "init_args": enc},
        "input_sort_field": "phi_calo",
        "input_sort_period": 2 * math.pi,
    }
    if gmp is not None:
        init["input_coord_fields"] = ["eta_calo", "phi_calo"] + (["depth_calo"] if depth else [])
    cfg = {"name": f"gmp_sweep_{name}", "model": {"model": {"init_args": init}}}
    if depth:
        cfg["data"] = {"gmp_depth": depth}
        if name in TRACK_DEPTH:
            cfg["data"]["gmp_track_depth"] = TRACK_DEPTH[name]
    return cfg


def write_configs(out: Path = SWEEP_DIR) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for name in ARMS:
        p = out / f"{name}.yaml"
        head = f"# GENERATED by `python -m hepattn.experiments.clic.gmp_ablation.sweep write-configs` (arm {name!r}); do not edit.\n"
        p.write_text(head + yaml.safe_dump(arm_config(name), sort_keys=False))
        paths.append(p)
    return paths


# ------------------------------------------------------------------------------------------------------- summary
def _metrics(run: Path) -> dict:
    files = sorted(run.rglob("metrics.csv"))
    if not files:
        return {}
    rows = list(csv.DictReader(files[-1].open()))
    out: dict = {"val": [], "train_loss_last": None}
    train = [float(r["train/loss"]) for r in rows if r.get("train/loss")]
    if train:
        tail = train[-max(1, len(train) // 10) :]
        out["train_loss_last"] = sum(tail) / len(tail)
    for r in rows:
        vals = {k: float(v) for k, v in r.items() if k.startswith("val/") and v not in {"", None}}
        if vals:
            out["val"].append({"epoch": int(float(r.get("epoch") or 0)), **vals})
    return out


def _diag(run: Path) -> dict:
    files = sorted(run.rglob("*.rank0.json"))
    return json.loads(files[-1].read_text()) if files else {}


def summarize(campaign: Path, geometry: Path | None = None) -> str:
    geo = json.loads(geometry.read_text())["neighbourhoods"] if geometry else {}
    lines = [f"# GMP sweep summary: {campaign}", ""]
    head = (
        "| arm | epochs | steps/s | epoch train min | peak GiB | params (GMP) | nonfinite loss/grad | train loss (last 10%) "
        "| val/loss by epoch | key val metrics (last epoch) |"
    )
    lines += [head, "|" + "---|" * 10]
    for run in sorted(p for p in campaign.iterdir() if p.is_dir() and (p / "arm.txt").exists()):
        arm = (run / "arm.txt").read_text().strip()
        d, m = _diag(run), _metrics(run)
        ep = d.get("epochs", [])
        last = m.get("val", [])[-1] if m.get("val") else {}
        key = {k: v for k, v in last.items() if any(s in k for s in ("eff", "pur", "accuracy", "exact"))}
        keys = ", ".join(f"{k.removeprefix('val/')}={v:.4f}" for k, v in sorted(key.items())[:6])
        params = d.get("params", {})
        health = d.get("health", {})
        vloss = " / ".join(f"{v['val/loss']:.4f}" for v in m.get("val", []) if "val/loss" in v)
        lines.append(
            f"| {arm} | {len(ep)} | {ep[-1]['steps_per_s']:.3f} | {ep[-1]['train_wall_s'] / 60:.1f} "
            f"| {ep[-1].get('peak_alloc_gib', float('nan')):.1f} "
            f"| {params.get('model_total', '?')} ({params.get('gmp_total', 0)}) | {health.get('nonfinite_loss_batches', '?')}/"
            f"{health.get('nonfinite_grad_steps', '?')} | {m.get('train_loss_last') or float('nan'):.4f} | {vloss} | {keys} |"
            if ep
            else f"| {arm} | 0 | - | - | - | - | - | - | - | (no finished epoch) |"
        )
    if geo:
        lines += [
            "",
            "## Neighbourhood statistics of the grids (geometry_study.py, validation events)",
            "",
            "| grid | occupied cells | neighbours/node | same-particle | purity | track's own cluster in reach | ECAL-HCAL pair frac |",
            "|---|---|---|---|---|---|---|",
        ]
        for name, s in geo.items():
            lines.append(
                f"| {name} | {s['occupied_cells_median']:.0f} | {s['neighbours_per_node_mean']:.2f} | {s['same_particle_neighbours_mean']:.2f} "
                f"| {s['purity']:.3f} | {s['track_own_cluster_in_reach']} | {s['ecal_hcal_pair_frac']:.3f} |"
            )
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("write-configs")
    s = sub.add_parser("summarize")
    s.add_argument("campaign", type=Path)
    s.add_argument("--geometry", type=Path)
    args = p.parse_args()
    if args.cmd == "write-configs":
        for path in write_configs():
            print(path)
    else:
        print(summarize(args.campaign, args.geometry))


if __name__ == "__main__":
    main()
